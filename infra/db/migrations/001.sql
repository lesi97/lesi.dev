CREATE OR REPLACE VIEW "public"."destiny_weapon_kill_summary" WITH ("security_invoker"='on') AS
 SELECT "u"."bungie_id",
    "w"."display_name" AS "weapon_name",
    "wkc"."pvp_kills",
    "wkc"."pve_kills",
    "wkc"."trials_kills"
   FROM (("public"."destiny_weapon_kill_counts" "wkc"
     JOIN "public"."destiny_users" "u" ON ((("u"."membership_id")::"text" = ("wkc"."membership_id")::"text")))
     JOIN "public"."destiny_weapons" "w" ON (("w"."id" = "wkc"."weapon_hash")))
  WHERE (1 = 1)
  ORDER BY ("wkc"."pvp_kills" IS NULL), "wkc"."pvp_kills" DESC, "u"."bungie_id";
