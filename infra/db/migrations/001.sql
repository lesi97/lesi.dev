CREATE OR REPLACE VIEW "public"."destiny_user_play_times" WITH ("security_invoker"='on') AS
 SELECT "u"."bungie_id",
    "sum"(
        CASE
            WHEN (("c"."character_type")::"text" = 'Warlock'::"text") THEN "c"."minutes_played"
            ELSE (0)::bigint
        END) AS "total_warlock_minutes",
    "sum"(
        CASE
            WHEN (("c"."character_type")::"text" = 'Hunter'::"text") THEN "c"."minutes_played"
            ELSE (0)::bigint
        END) AS "total_hunter_minutes",
    "sum"(
        CASE
            WHEN (("c"."character_type")::"text" = 'Titan'::"text") THEN "c"."minutes_played"
            ELSE (0)::bigint
        END) AS "total_titan_minutes"
   FROM ("public"."destiny_user_characters" "c"
     JOIN "public"."destiny_users" "u" ON ((("u"."membership_id")::"text" = ("c"."membership_id")::"text")))
  GROUP BY "u"."bungie_id";
ALTER TABLE "public"."destiny_user_play_times" OWNER TO "postgres";


